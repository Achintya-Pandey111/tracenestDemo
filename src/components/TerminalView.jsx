import React, { useState } from 'react';
import { Terminal, Copy, Check } from 'lucide-react';

export default function TerminalView({ terminalOutput = '' }) {
  const [copied, setCopied] = useState(false);

  const copyText = () => {
    navigator.clipboard.writeText(terminalOutput);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <div className="rounded-xl border border-white/5 bg-dark-900/90 shadow-2xl overflow-hidden font-mono text-xs">
      
      {/* Terminal Titlebar */}
      <div className="px-4 py-2.5 bg-dark-850 border-b border-white/5 flex items-center justify-between">
        <div className="flex items-center space-x-2">
          <div className="w-2.5 h-2.5 rounded-full bg-rose-500/80" />
          <div className="w-2.5 h-2.5 rounded-full bg-amber-500/80" />
          <div className="w-2.5 h-2.5 rounded-full bg-emerald-500/80" />
          <span className="ml-2 text-zinc-400 text-[11px] font-medium flex items-center space-x-1">
            <Terminal className="w-3 h-3 text-brand-primary" />
            <span>TraceNest CLI Reporter Output (TraceNest.report())</span>
          </span>
        </div>

        <button
          onClick={copyText}
          className="flex items-center space-x-1 px-2.5 py-1 rounded bg-dark-800 hover:bg-dark-750 text-zinc-300 hover:text-white border border-zinc-700/60 transition-colors text-[11px]"
        >
          {copied ? (
            <>
              <Check className="w-3 h-3 text-emerald-400" />
              <span className="text-emerald-400">Copied</span>
            </>
          ) : (
            <>
              <Copy className="w-3 h-3" />
              <span>Copy Output</span>
            </>
          )}
        </button>
      </div>

      {/* Terminal Body */}
      <div className="p-4 sm:p-5 bg-black/75 overflow-x-auto max-h-[500px]">
        <pre className="text-zinc-300 whitespace-pre font-mono leading-relaxed text-[11px] sm:text-xs">
          {terminalOutput || 'No terminal report available.'}
        </pre>
      </div>

      {/* Terminal Footer tip */}
      <div className="px-4 py-2 bg-dark-950 border-t border-zinc-850 text-[11px] text-zinc-500 flex items-center justify-between">
        <span>Generated by <code className="text-indigo-400">tracenest-node</code> ConsoleReporter</span>
        <span className="hidden sm:inline">Run in CLI via: <code className="text-zinc-400">npx tracenest report trace.json</code></span>
      </div>

    </div>
  );
}
